/**
 * Helper to compute the dynamic hour slot based on full 24-hour system time and optional manual offset
 */
export function getSystemHourSlot(offsetHours: number = 0): number {
  const now = new Date();
  const currentHour = now.getHours();
  return (currentHour + offsetHours + 240) % 24;
}

/**
 * Calculates remaining seconds until the next exact hour strikes
 */
export function getRemainingSecondsUntilNextHour(): number {
  const now = new Date();
  const minutes = now.getMinutes();
  const seconds = now.getSeconds();
  return (60 - minutes - 1) * 60 + (60 - seconds);
}
