export function getHourlyLeadStory(manualIndex?: number, langCode?: string): Article {
  const list = HOURLY_BREAKING_LEAD_STORIES;
  const currentHour = new Date().getHours();
  const effectiveIndex = typeof manualIndex === 'number' && manualIndex >= 0 ? manualIndex : currentHour;
  const baseStory = list[effectiveIndex % list.length];

  if (!langCode || langCode === 'en') {
    return baseStory;
  }

  const translatedData = HOURLY_TRANSLATIONS[langCode]?.[baseStory.id];
  const mergedStory: Article = translatedData
    ? {
        ...baseStory,
        title: translatedData.title,
        deck: translatedData.deck,
        category: translatedData.category || baseStory.category,
        leadParagraph: translatedData.leadParagraph || baseStory.leadParagraph,
      }
    : baseStory;

  return translateArticle(mergedStory, langCode);
}
